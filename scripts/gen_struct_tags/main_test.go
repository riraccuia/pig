func generateOne(t *testing.T, filename string, src []byte, allow map[string]bool) (string, []byte, map[string]bool) {
	t.Helper()
	files, found, err := generate(filename, src, allow)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if len(files) == 0 {
		return "", nil, found
	}
	return files[0].path, files[0].data, found
}

func TestGenerate(t *testing.T) {
	in := `package p

type S struct {
	// desc=Tunnel identifier
	Name string ` + tag(`toml:"name"`) + `
}

type Other struct {
	// desc=should not appear
	Skip int ` + tag(`toml:"skip"`) + `
}
`
	path, out, found := generateOne(t, "t.go", []byte(in), toSet([]string{"S"}))
	if !strings.HasSuffix(path, "zfielddocs_S.go") {
		t.Fatalf("path = %q", path)
	}
	if !found["S"] {
		t.Fatal("expected S to be found")
	}
	if found["Other"] {
		t.Fatal("did not expect Other to be found")
	}
	want := formatted(t, `// Code generated by gen_struct_tags; DO NOT EDIT.

package p

import "github.com/riraccuia/pig/pkg/common"

func (S) DescribeFields() map[string]common.FieldMeta {
	return map[string]common.FieldMeta{
		"name": {Desc: "Tunnel identifier"},
	}
}
`)
	if string(out) != want {
		t.Fatalf("output mismatch\ngot:\n%s\nwant:\n%s", out, want)
	}
}

func TestGenerateRecursive(t *testing.T) {
	in := `package p

type Root struct {
	// desc=logging
	Log Log ` + tag(`toml:"log"`) + `
	// desc=tunnels
	Tunnels []Tun ` + tag(`toml:"tunnels"`) + `
}

type Log struct {
	// desc=path to log
	File string ` + tag(`toml:"file"`) + `
}

type Tun struct {
	// desc=tunnel id
	Name string ` + tag(`toml:"name"`) + `
}

type Other struct {
	// desc=skip me
	X int ` + tag(`toml:"x"`) + `
}
`
	_, out, found := generateOne(t, "t.go", []byte(in), toSet([]string{"Root"}))
	if !found["Root"] || found["Log"] || found["Tun"] || found["Other"] {
		t.Fatalf("found = %#v", found)
	}
	got := string(out)
	if strings.Contains(got, "func (Log)") || strings.Contains(got, "func (Tun)") {
		t.Fatalf("generated methods for child types:\n%s", got)
	}
	for _, want := range []string{
		`"log":`,
		`Desc: "logging"`,
		`"log.file"`,
		`Desc: "path to log"`,
		`"tunnels":`,
		`"tunnels[].name"`,
		`Desc: "tunnel id"`,
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("missing %s in:\n%s", want, got)
		}
	}
	if strings.Contains(got, `"x"`) {
		t.Fatalf("unrelated type leaked into map:\n%s", got)
	}
}

