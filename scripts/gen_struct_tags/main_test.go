func TestGenerateDirectives(t *testing.T) {
	in := `package p

type S struct {
	// default=DefaultMTU
	// optional=true
	// desc=Maximum Transmission Unit.
	MTU int ` + tag(`toml:"mtu"`) + `
}
`
	_, out, _ := generateOne(t, "t.go", []byte(in), toSet([]string{"S"}))
	got := string(out)
	if !strings.Contains(got, `Default: fmt.Sprint(DefaultMTU)`) {
		t.Fatalf("default expression not copied:\n%s", got)
	}
	if !strings.Contains(got, `Optional: true`) {
		t.Fatalf("missing optional:\n%s", got)
	}
	if !strings.Contains(got, `Desc: "Maximum Transmission Unit."`) {
		t.Fatalf("missing desc:\n%s", got)
	}
	if !strings.Contains(got, `"fmt"`) {
		t.Fatalf("expected fmt import:\n%s", got)
	}
}

