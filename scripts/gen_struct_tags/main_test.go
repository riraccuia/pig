func tag(s string) string {
	return "`" + s + "`"
}

func formatted(t *testing.T, s string) string {
	t.Helper()
	out, err := format.Source([]byte(s))
	if err != nil {
		t.Fatalf("format: %v\n%s", err, s)
	}
	return string(out)
}
