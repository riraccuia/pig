func TestGenerateMultipleTypes(t *testing.T) {
	in := `package p

type A struct {
	// desc=from A
	X int ` + tag(`toml:"x"`) + `
}

type B struct {
	// desc=from B
	X int ` + tag(`toml:"x"`) + `
}
`
	files, found, err := generate("t.go", []byte(in), toSet([]string{"A", "B"}))
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if !found["A"] || !found["B"] {
		t.Fatalf("found = %#v", found)
	}
	if len(files) != 2 {
		t.Fatalf("got %d files, want 2", len(files))
	}
	byName := map[string]string{}
	for _, f := range files {
		byName[filepath.Base(f.path)] = string(f.data)
	}
	if !strings.Contains(byName["zfielddocs_A.go"], "func (A) DescribeFields()") {
		t.Fatal("missing A method")
	}
	if !strings.Contains(byName["zfielddocs_B.go"], "func (B) DescribeFields()") {
		t.Fatal("missing B method")
	}
}

func TestGenerateIdempotent(t *testing.T) {
	in := `package p

type S struct {
	// desc=Tunnel identifier
	Name string ` + tag(`toml:"name"`) + `
}
`
	allow := toSet([]string{"S"})
	_, first, _ := generateOne(t, "t.go", []byte(in), allow)
	_, second, _ := generateOne(t, "t.go", []byte(in), allow)
	if string(first) != string(second) {
		t.Fatalf("non-idempotent\nfirst:\n%s\nsecond:\n%s", first, second)
	}
}

